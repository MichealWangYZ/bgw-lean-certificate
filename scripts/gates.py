def select_fast(changed):
    """(test modules, unsure files, archived files) for the changed paths.

    Lean files under GW/ that a FAST entry names (e.g. HubbardDimer*.lean) select that
    test as well. The Lean build and the audit still cover them."""
    chosen, unsure, archived = set(), [], []
    for f in changed:
        hit = {t for t, prefixes in FAST.items() if any(f.startswith(p) for p in prefixes)}
        chosen |= hit
        if hit:
            continue
        if f.startswith(ARCHIVED_PATHS):
            archived.append(f)
        elif not f.startswith(NO_PYTHON_TEST):
            unsure.append(f)
    if unsure:
        chosen = set(FAST)
    return sorted(chosen), unsure, archived
