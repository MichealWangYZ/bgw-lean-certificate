"""Which test modules belong to the scientific gate and which to the workflow gate.

THE CRITERION, stated once so it can be applied consistently:

    A test belongs to the WORKFLOW gate if REWORDING ALONE can fail it --
    that is, if it can go red with no numerical, algebraic or source-mapping
    change whatsoever. Everything else is SCIENTIFIC.

Why the split exists. An external reviewer observed that this project's test
suite had grown to mix two different questions: "is the measured number right"
and "does the project's own prose still say the true thing". Both matter, but
conflating them means a docstring rewrite can fail the gate that is supposed
to protect the physics, and three consecutive repair passes here did exactly
that. Separating them lets a reader see which kind of thing broke.

The split is NOT a quality ranking. Every workflow test exists because a
specific written claim was found to be false, and a reader acts on prose. The
scientific gate is the one that must never be weakened; the workflow gate is
the one that must never be quietly deleted when it becomes inconvenient.

Both gates run by default. `scripts/verify.py --gate scientific` and
`--gate workflow` run one of them. `--gate fast` is the routine-change gate
(see FAST below).

The SCIENTIFIC and WORKFLOW tuples are GENERATED by `scripts/registry.py`. The
rule: a test module is WORKFLOW iff the first line of its docstring starts
with `WORKFLOW GATE`. Every other module is SCIENTIFIC.

`tests/test_gate_partition.py` enforces that every discovered test module is
classified here exactly once, so a new test file cannot silently escape both
gates -- which would make it look like it is running when it is not.
"""

